export function epochForYear(year) {
  return WorldData.epochs.find(epoch => year >= epoch.startYear && year <= epoch.endYear) ?? WorldData.epochs[0];
}

export function periodForYear(year) {
  if (year < WorldData.map.disasterYear) return 'before';
  if (year === WorldData.map.disasterYear) return 'event';
  return 'after';
}
